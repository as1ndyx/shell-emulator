package shell

import (
	"bufio"
	"errors"
	"fmt"
	"io"
)

// Run запускает цикл «чтение — выполнение — вывод» (REPL):
// печатает приглашение в out, читает команды из in построчно и выводит
// результат. Цикл завершается по команде exit или по концу входного
// потока: пользователь нажал Ctrl+D либо дочитан файл со списком команд.
//
// Приглашение печатается без перевода строки, чтобы курсор оставался
// рядом с ним, как в настоящем терминале. Когда ввод закончился,
// печатается перевод строки, чтобы вывод не слипся с приглашением
// реальной оболочки.
//
// Источник и приёмник передаются аргументами, а не берутся из os напрямую:
// благодаря этому вместо клавиатуры и экрана можно подставить файл или
// строку в памяти, что используется в тестах.
func Run(in io.Reader, out io.Writer) {
	scanner := bufio.NewScanner(in)
	for {
		fmt.Fprint(out, Prompt())

		if !scanner.Scan() {
			fmt.Fprintln(out)
			return
		}

		if handle(scanner.Text(), out) {
			return
		}
	}
}

// handle обрабатывает одну строку ввода и печатает результат в out.
// Возвращает true только для команды exit — единственного случая, когда
// цикл прерывается по воле пользователя. Ошибка печатается, но работа
// продолжается: опечатка не должна закрывать эмулятор. Пустой вывод
// не печатается, чтобы пустой ввод не порождал лишних строк.
func handle(line string, out io.Writer) bool {
	output, err := Execute(Parse(line))
	switch {
	case errors.Is(err, ErrExit):
		return true
	case err != nil:
		fmt.Fprintln(out, "ошибка:", err)
	case output != "":
		fmt.Fprintln(out, output)
	}
	return false
}
